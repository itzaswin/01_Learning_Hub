# Catorgories of keywords in Python
# Option with keyword Examples

# 1. Value Keywords: These keywords represent constant values in Python. They include:
# False, None, True

# 2. Control Flow Keywords: These keywords are used to control the flow of execution in a program. They include:
# if, else, elif, for, while, break, continue, pass

# 3. Function and Class Definition Keywords: These keywords are used to define functions and classes in Python. They include:
# def, class, lambda

# 4. Exception Handling Keywords: These keywords are used to handle exceptions in Python. They include:
# try, except, finally, raise

# 5. Operator Keywords: These keywords are used to perform operations in Python. They include:
# and, or, not, is, in

# 6. Context Management Keywords: These keywords are used to manage resources in Python. They include:
# with, as

# 7. Import and Global Keywords: These keywords are used to import modules and declare global variables in Python. They include:
# import, from, global, nonlocal

# 8. Assertion Keyword: This keyword is used to assert a condition in Python. It includes:
# assert

# 9. Del Keyword: This keyword is used to delete objects in Python. It includes:
# del

# 10. Scope Keywords and Namespace Keywords: These keywords are used to define the scope of variables in Python. They include:  
# global, nonlocal

# 11. Return Keyword: This keyword is used to return a value from a function in Python. It includes:
# return

# 12. Yield Keyword: This keyword is used to create a generator in Python. It includes:
# yield

# 13. Async and Await Keywords: These keywords are used to define asynchronous functions and to wait for asynchronous operations in Python. They include:
# async, await

